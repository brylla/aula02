// (adição, subtração, multiplicação, divisão)

var n1 = 3
var n2 = 2
var operacao = "*"

if (operacao == "+") {
    console.log(n1 + n2)
} else if (operacao == "-") {
    console.log(n1 - n2)
} else if (operacao == "*") {
    console.log(n1 * n2)
} else if (operacao == "/") {
    console.log(n1 / n2)
} else {
    console.log("Operação não é valida")
}