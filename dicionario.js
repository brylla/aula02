// string = textos
// boolean = verdadeiro/false
// float = numeros "quebrados" com virgulas
// int = numeros inteiros 

// variaveis 
var idadeUsuario = 17

// exibe mensagem na tela 
// o simbolo "+" quando usado com texto a funcao dele é "concatenar"
console.log("idade do usuario: " + idadeUsuario)

// "=" é o simbolo de atribuição 
// "==" é o operador de comparação iguais
// ">" é o operador maior
// "<" é o operador menor
// ">=" é o operador maior ou igual
// "<=" é o operador menor ou igual
console.log(idadeUsuario>=18)
// ao ter a comparação eu tenho resultado em boolean

// "if" significa "se" - pergunta e executa se for verdade
// "else" significa "senao" - executa caso o if for falso
if (idadeUsuario>=18) {
    console.log("O usuario pode dirigir!")
} else {
    console.log("Desculpa, você ainda não pode dirigir!")
} 



